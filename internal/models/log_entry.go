package models

import (
	"time"
)

// Severity levels for log entries
type Severity int

const (
	SeverityDebug Severity = iota
	SeverityInfo
	SeverityNotice
	SeverityWarning
	SeverityError
	SeverityCritical
	SeverityAlert
	SeverityEmergency
)

var severityNames = map[Severity]string{
	SeverityDebug:     "DEBUG",
	SeverityInfo:      "INFO",
	SeverityNotice:    "NOTICE",
	SeverityWarning:   "WARNING",
	SeverityError:     "ERROR",
	SeverityCritical:  "CRITICAL",
	SeverityAlert:     "ALERT",
	SeverityEmergency: "EMERGENCY",
}

func (s Severity) String() string {
	if name, ok := severityNames[s]; ok {
		return name
	}
	return "UNKNOWN"
}

// LogEntry represents a normalized log entry
type LogEntry struct {
	ID        string                 `json:"id"`
	Timestamp time.Time              `json:"timestamp"`
	Source    string                 `json:"source"`   // Hostname or IP
	Facility  string                 `json:"facility"` // syslog facility or log type
	Severity  Severity               `json:"severity"`
	Message   string                 `json:"message"`
	RawLog    string                 `json:"raw_log"`
	Fields    map[string]interface{} `json:"fields"` // Extracted fields
	Tags      []string               `json:"tags"`   // For categorization
}

// Alert represents a security alert generated by detection rules
type Alert struct {
	ID          string                 `json:"id"`
	Timestamp   time.Time              `json:"timestamp"`
	RuleName    string                 `json:"rule_name"`
	Severity    string                 `json:"severity"` // low, medium, high, critical
	Description string                 `json:"description"`
	RelatedLogs []string               `json:"related_logs"` // Log entry IDs
	Details     map[string]interface{} `json:"details"`
	Count       int                    `json:"count"` // For aggregated alerts
}

// DetectionRule defines a security detection rule
type DetectionRule struct {
	Name        string                 `yaml:"name"`
	Enabled     bool                   `yaml:"enabled"`
	Severity    string                 `yaml:"severity"`
	Description string                 `yaml:"description"`
	Conditions  map[string]interface{} `yaml:"conditions"`
	Threshold   int                    `yaml:"threshold,omitempty"`
	TimeWindow  string                 `yaml:"time_window,omitempty"` // e.g., "5m", "1h"
}

// Config represents the application configuration
type Config struct {
	Rules []DetectionRule `yaml:"rules"`

	// Time-based anomaly settings
	NormalHours struct {
		Start int `yaml:"start"` // 0-23
		End   int `yaml:"end"`   // 0-23
	} `yaml:"normal_hours"`

	// General settings
	MaxLogEntries int `yaml:"max_log_entries"`
}
