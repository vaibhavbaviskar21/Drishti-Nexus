package models

import (
	"time"
)

// Severity levels for log entries
type Severity int

const (
	SeverityDebug Severity = iota
	SeverityInfo
	SeverityNotice
	SeverityWarning
	SeverityError
	SeverityCritical
	SeverityAlert
	SeverityEmergency
)

var severityNames = map[Severity]string{
	SeverityDebug:     "DEBUG",
	SeverityInfo:      "INFO",
	SeverityNotice:    "NOTICE",
	SeverityWarning:   "WARNING",
	SeverityError:     "ERROR",
	SeverityCritical:  "CRITICAL",
	SeverityAlert:     "ALERT",
	SeverityEmergency: "EMERGENCY",
}

func (s Severity) String() string {
	if name, ok := severityNames[s]; ok {
		return name
	}
	return "UNKNOWN"
}

// ParseQuality describes how much of an entry was recovered by a structured parser.
const (
	// QualityClean: a format-specific parser matched and every field, including the timestamp, is exact.
	QualityClean = "Clean"
	// QualityPartial: a format-specific parser matched, but something was repaired or assumed
	// (bad encoding, truncated line, ambiguous/nonexistent DST wall-clock time, inferred year).
	QualityPartial = "Partial"
	// QualityBestEffort: no structured parser matched; the generic fallback kept the raw text.
	QualityBestEffort = "BestEffort"
)

// LogEntry represents a normalized log entry
type LogEntry struct {
	ID           string                 `json:"id"`        // "<source-label>:<line>" — cites the exact evidence line
	Timestamp    time.Time              `json:"timestamp"` // always UTC
	Source       string                 `json:"source"`    // Hostname or IP
	Facility     string                 `json:"facility"`  // syslog facility or log type
	Severity     Severity               `json:"severity"`
	Message      string                 `json:"message"`
	RawLog       string                 `json:"raw_log"`
	ParseQuality string                 `json:"parse_quality"` // QualityClean, QualityPartial, QualityBestEffort
	Parser       string                 `json:"parser"`        // name of the parser that produced the entry
	LineNumber   int                    `json:"line_number"`   // first physical line of the entry in the source file
	Fields       map[string]interface{} `json:"fields"`        // Extracted fields
	Tags         []string               `json:"tags"`          // For categorization
}

// Alert represents a security alert generated by detection rules
type Alert struct {
	ID             string                 `json:"id"`
	IncidentID     string                 `json:"incident_id,omitempty"` // Groups alerts from the same actor/host and timeframe
	CorrelationKey string                 `json:"correlation_key"`       // e.g. "host=web01|ip=10.0.0.5"
	Timestamp      time.Time              `json:"timestamp"`             // first occurrence
	LastSeen       time.Time              `json:"last_seen"`             // last aggregated occurrence
	RuleName       string                 `json:"rule_name"`
	Severity       string                 `json:"severity"` // low, medium, high, critical
	Description    string                 `json:"description"`
	RelatedLogs    []string               `json:"related_logs"`             // Log entry IDs (capped)
	RelatedAlerts  []string               `json:"related_alerts,omitempty"` // Alerts describing the same underlying activity
	Details        map[string]interface{} `json:"details"`
	Count          int                    `json:"count"` // number of times the rule matched within the aggregation window

	// MITRE ATT&CK mapping (Phase 2.3)
	MITRETechniqueID   string `json:"mitre_technique_id,omitempty"`   // e.g. "T1110", "T1059"
	MITRETechniqueName string `json:"mitre_technique_name,omitempty"` // e.g. "Brute Force"
	MITRETactic        string `json:"mitre_tactic,omitempty"`         // e.g. "Credential Access"
}

// DetectionRule defines a security detection rule
type DetectionRule struct {
	Name        string                 `yaml:"name" json:"name"`
	Enabled     bool                   `yaml:"enabled" json:"enabled"`
	Severity    string                 `yaml:"severity" json:"severity"`
	Description string                 `yaml:"description" json:"description,omitempty"`
	Conditions  map[string]interface{} `yaml:"conditions" json:"conditions,omitempty"`
	Threshold   int                    `yaml:"threshold,omitempty" json:"threshold,omitempty"`
	TimeWindow  string                 `yaml:"time_window,omitempty" json:"time_window,omitempty"` // e.g., "5m", "1h"
}

// NormalHours is the configured business-hours window (hours 0-23, in Timezone).
type NormalHours struct {
	Start    int    `yaml:"start" json:"start"`
	End      int    `yaml:"end" json:"end"`
	Timezone string `yaml:"timezone,omitempty" json:"timezone,omitempty"` // IANA name, default UTC
}

// Config represents the application configuration
type Config struct {
	Rules []DetectionRule `yaml:"rules" json:"rules"`

	// Time-based anomaly settings
	NormalHours NormalHours `yaml:"normal_hours" json:"normal_hours"`

	// Alerts sharing a correlation key are grouped into one incident while they are
	// no more than this far apart in event time (Go duration, default "30m").
	IncidentGap string `yaml:"incident_gap" json:"incident_gap"`

	// General settings
	MaxLogEntries int `yaml:"max_log_entries" json:"max_log_entries"`
}
