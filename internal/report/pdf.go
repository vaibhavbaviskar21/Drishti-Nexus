package report

import (
	"drishti-nexus/internal/detection"
	"fmt"
	"io"
	"strings"
)

var severityColor = map[string]rgb{
	"critical": {0.61, 0.11, 0.11},
	"high":     {0.76, 0.25, 0.05},
	"medium":   {0.63, 0.38, 0.03},
	"low":      {0.25, 0.38, 0.07},
}

// WritePDF writes the same report as WriteHTML, as a PDF for case files.
func WritePDF(w io.Writer, d Data) error {
	p := &pdfDoc{}
	s := d.Session
	h := func(title string) {
		p.need(40)
		p.y -= 14
		p.text(marginX, p.y-13, bold, 13, black, title)
		p.y -= 18
		p.rect(marginX, p.y, contentW, 1, black)
		p.y -= 6
	}
	kv := func(k, v string) {
		p.row(8.5, false, cell{140, bold, black, k}, cell{contentW - 140, regular, black, v})
	}
	kvMono := func(k, v string) { p.row(8, false, cell{140, bold, black, k}, cell{contentW - 140, mono, black, v}) }

	p.newPage()
	p.text(marginX, p.y-20, bold, 20, black, "Drishti Nexus - Incident Report")
	p.y -= 30
	p.para(marginX, regular, 9, muted, fmt.Sprintf("Session %s · generated %s · tool %s", s.SessionID, fmtTime(d.GeneratedAt), s.ToolVersion))
	p.para(marginX, regular, 9, muted, "All findings are produced by deterministic, explainable detection rules. Every alert cites the evidence lines it is based on (<file>:<line>).")

	h("1. Summary")
	st := d.Stats
	kv("Incidents / alerts", fmt.Sprintf("%d / %d", st.Incidents, st.Alerts))
	kv("Entries / lines", fmt.Sprintf("%d / %d", st.Entries, st.Lines))
	kv("Evidence files", fmt.Sprint(len(s.Evidence)))
	kv("Analysis time", fmt.Sprintf("%d ms", st.DurationMs))
	for _, r := range d.Rules {
		kv(r.Name, fmt.Sprintf("%d alerts", r.N))
	}
	for _, t := range d.Techniques {
		kv("ATT&CK "+t.ID, fmt.Sprintf("%s (%s): %d alerts", t.Name, t.Tactic, t.Alerts))
		if len(t.Controls) > 0 {
			kv("  Compliance refs", controlList(t.Controls))
		}
	}
	if len(d.Techniques) > 0 {
		p.para(marginX, regular, 8, muted, "Compliance references point auditors to the controls these alerts are evidence for; they are not a compliance assessment. Every scan also supports "+controlList(detection.MonitoringControls)+".")
	}

	h("2. Parse quality")
	for _, c := range d.Quality {
		kv(c.Name, fmt.Sprintf("%d (%.1f%%)", c.N, c.Pct))
	}
	for _, c := range d.Parsers {
		kv("Parser "+c.Name, fmt.Sprintf("%d (%.1f%%)", c.N, c.Pct))
	}
	for _, c := range d.Repairs {
		kv("Repair "+c.Name, fmt.Sprint(c.N))
	}

	h("3. Incidents")
	if len(d.Incidents) == 0 {
		p.para(marginX, regular, 9, black, "No alerts were raised.")
	}
	for _, inc := range d.Incidents {
		p.need(60)
		p.y -= 6
		p.rect(marginX, p.y-16, contentW, 16, panel)
		p.rect(marginX, p.y-16, 4, 16, severityColor[strings.ToLower(inc.Severity)])
		p.text(marginX+10, p.y-12, bold, 10.5, black, winAnsi(fmt.Sprintf("%s   %s   %s -> %s   %d alerts",
			inc.ID, strings.ToUpper(inc.Severity), fmtTime(inc.Start), fmtTime(inc.End), len(inc.Alerts))))
		p.y -= 20
		if len(inc.Techniques) > 0 {
			p.para(marginX, regular, 8.5, black, "ATT&CK: "+strings.Join(inc.Techniques, ", "))
		}
		p.para(marginX, mono, 7.5, muted, strings.Join(inc.Keys, "; "))
		for _, a := range inc.Alerts {
			p.need(50)
			p.y -= 4
			p.rect(marginX+4, p.y-11, 3, 11, severityColor[strings.ToLower(a.Severity)])
			p.para(marginX+12, bold, 9.5, black, fmt.Sprintf("%s  [%s]  %s  (%s)", fmtTime(a.Timestamp), strings.ToUpper(a.Severity), a.RuleName, a.ID))
			if a.Count > 1 {
				p.para(marginX+12, regular, 8.5, muted, fmt.Sprintf("%d matches until %s", a.Count, fmtTime(a.LastSeen)))
			}
			p.para(marginX+12, regular, 9, black, a.Description)
			if a.MITRETechniqueID != "" {
				p.para(marginX+12, regular, 8.5, black, strings.TrimSpace(fmt.Sprintf("ATT&CK %s %s · %s", a.MITRETechniqueID, a.MITRETechniqueName, a.MITRETactic)))
			}
			var det []string
			for _, kv := range a.Details {
				det = append(det, kv.Key+"="+kv.Value)
			}
			if len(det) > 0 {
				p.para(marginX+12, regular, 8, muted, strings.Join(det, "   "))
			}
			if len(a.RelatedAlerts) > 0 {
				p.para(marginX+12, regular, 8, muted, "Related alerts: "+strings.Join(a.RelatedAlerts, ", "))
			}
			for i, l := range a.Evidence {
				head, text := l.ID, "entry not retained in this run (alerts-only or store cap); the line is in the evidence file at this ID"
				if l.Found {
					head, text = l.ID+"   "+fmtTime(l.Time)+"   "+l.Source, l.Text
				}
				p.row(7, i%2 == 0, cell{contentW, bold, black, head})
				p.row(7, i%2 == 0, cell{12, mono, black, ""}, cell{contentW - 12, mono, black, text})
			}
			if a.Omitted > 0 {
				p.para(marginX+12, regular, 8, muted, fmt.Sprintf("+%d more cited lines, listed in the JSON report", a.Omitted))
			}
		}
	}

	if len(d.AISummaries) > 0 {
		h("AI-generated summaries (NOT evidence)")
		p.para(marginX, bold, 9, red, "These narratives were generated by a language model from the deterministic findings above. They are not evidence and are not part of the detection results. Verify every statement against the cited alerts and evidence lines.")
		for _, ai := range d.AISummaries {
			status, c := "NOT verified against the incident data", red
			if ai.Verified {
				status, c = "all claims matched the incident data", green
			}
			p.y -= 4
			p.para(marginX, bold, 9.5, black, ai.IncidentID+" · model "+ai.Model)
			p.para(marginX, bold, 8.5, c, status)
			p.para(marginX, regular, 9, black, ai.Text)
			for _, u := range ai.Unsupported {
				p.para(marginX+12, regular, 8.5, red, "Unsupported claim: "+u)
			}
		}
	}

	h("4. Chain of custody")
	p.para(marginX, regular, 8.5, muted, "Evidence was opened read-only. Each file is hashed before analysis and re-hashed afterwards; a mismatch means it changed during analysis.")
	for _, ev := range s.Evidence {
		p.y -= 4
		kvMono("Evidence file", fmt.Sprintf("%s (%d bytes)", ev.Path, ev.SizeBytes))
		kvMono("SHA-256 before", ev.SHA256Before)
		kvMono("SHA-256 after", ev.SHA256After)
		u := unchanged(ev)
		c := red
		if u == "unchanged" {
			c = green
		}
		p.row(8.5, false, cell{140, bold, black, "Check"}, cell{contentW - 140, bold, c, u})
	}
	p.y -= 4
	if s.Config.ConfigPath != "" {
		kvMono("Detection config", s.Config.ConfigPath+"  sha256 "+s.Config.ConfigSHA256)
	} else {
		kv("Detection config", "built-in defaults")
	}
	for _, f := range s.Config.Definitions {
		kvMono("Definition file", f.Path+"  sha256 "+f.SHA256)
	}
	for _, f := range s.Outputs {
		kvMono("Output", f.Path+"  sha256 "+f.SHA256)
	}
	p.para(marginX, regular, 8, muted, "This report file is itself hashed in the session_end record of the audit log.")

	h("5. Audit session")
	kvMono("Session ID", s.SessionID)
	kvMono("Command", s.Command+" "+strings.Join(s.Args, " "))
	kv("Analyst (OS user)", s.OSUser+" on "+s.Hostname)
	kv("Tool", fmt.Sprintf("Drishti Nexus %s (%s, %s)", s.ToolVersion, s.GoVersion, s.Platform))
	kv("Started", fmtTime(s.StartedAt))
	kv("Report generated", fmtTime(d.GeneratedAt)+" (the session_end record follows in the audit log)")
	if s.RecordHash != "" {
		kvMono("session_start record hash", s.RecordHash)
	}
	kv("Normal hours", s.Config.NormalHours)
	kv("Incident gap", s.Config.IncidentGap)
	kv("Adaptive thresholds", s.Config.Adaptive)
	kv("Assumed timezone", s.Config.AssumedTimezone)
	kv("Storage", s.Config.Storage)
	p.y -= 4
	p.row(8, true, cell{200, bold, black, "Rule"}, cell{60, bold, black, "Enabled"}, cell{70, bold, black, "Severity"}, cell{70, bold, black, "Threshold"}, cell{contentW - 400, bold, black, "Window"})
	for _, r := range s.Config.Rules {
		th := "-"
		if r.Threshold > 0 {
			th = fmt.Sprint(r.Threshold)
		}
		p.row(8, false, cell{200, regular, black, r.Name}, cell{60, regular, black, fmt.Sprint(r.Enabled)}, cell{70, regular, black, r.Severity}, cell{70, regular, black, th}, cell{contentW - 400, regular, black, r.Window})
	}
	for _, wn := range s.Config.Warnings {
		p.para(marginX, regular, 8.5, red, "Warning: "+wn)
	}

	for i, pg := range p.pages {
		p.page = pg
		p.text(marginX, 30, regular, 7.5, muted, winAnsi(fmt.Sprintf("Drishti Nexus incident report · session %s · page %d of %d", s.SessionID, i+1, len(p.pages))))
	}
	return p.write(w, "Drishti Nexus incident report - session "+s.SessionID)
}

// controlList renders controls grouped by framework, in mapping order:
// "PCI DSS 4.0.1 8.3.4, 10.2.1.4; ISO/IEC 27001:2022 A.8.5; HIPAA 164.312(d)".
func controlList(cs []detection.Control) string {
	var parts []string
	for i, c := range cs {
		if i > 0 && cs[i-1].Framework == c.Framework {
			parts[len(parts)-1] += ", " + c.ID
			continue
		}
		parts = append(parts, c.Framework+" "+c.ID)
	}
	return strings.Join(parts, "; ")
}
